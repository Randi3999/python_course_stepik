"""
Даны пять чисел a1, a2, a3, a4, a5. Напишите программу, которая вычисляет сумму их модулей ∣a1∣+∣a2∣+∣a3∣+∣a4∣+∣a5∣.

Формат входных данных
На вход программе подаются пять действительных чисел a1, a2, a3, a4, a5, каждое на отдельной строке.

Формат выходных данных
Программа должна вывести одно число – сумму модулей введённых чисел.
"""
n1 = float(input())
n2 = float(input())
n3 = float(input())
n4 = float(input())
n5 = float(input())
print(abs(n1) + abs(n2) + abs(n3) + abs(n4) + abs(n5))
